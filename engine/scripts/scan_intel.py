def main() -> int:
    snapshot, evidence = load()
    speed = velocities(snapshot, evidence)
    results = assessments(evidence, speed)

    documents = {
        "SCAN.md": render_scan(snapshot),
        "ENTERPRISE_RESEARCH.md": render_enterprise(evidence, speed),
        "ARCHITECTURE.md": render_architecture(evidence),
        "FEATURE_MATRIX.md": render_features(evidence),
        "OPPORTUNITY_MATRIX.md": render_opportunity(results, speed),
        "COMPETITIVE_INTEL.md": render_competitive(results, speed),
        "REVENUE_MATRIX.md": render_revenue(),
        "TECH_RADAR.md": render_radar(evidence, speed),
        "RISK.md": render_risk(evidence, speed),
        "ROADMAP.md": render_roadmap(),
        "STRATEGY.md": render_strategy(results, speed),
        "OMNEX_ACTIONS.md": render_actions(evidence),
    }

    INTEL.mkdir(parents=True, exist_ok=True)
    failed = 0
    for name, body in documents.items():
        (INTEL / name).write_text(body)
        result = verify_document(body, evidence)
        status = "ok" if result.publishable else "REFUSED"
        print(
            f"{name:<26} {len(body.splitlines()):>4} lines  "
            f"{result.citations_checked:>3} citations  {status}"
        )
        if not result.publishable:
            failed += 1
            for finding in result.fatal:
                print(finding.report())

    velocity_counts = Counter("stalled" if v.stalled else "growing" for v in speed.values())
    print(
        f"\n{len(documents)} documents · {len(evidence.artifacts)} artifacts · "
        f"{len(speed)} velocities ({velocity_counts['growing']} growing, "
        f"{velocity_counts['stalled']} stalled)"
    )
    if failed:
        print(f"\n{failed} document(s) failed verification and must not be published")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())

# ── loading ───────────────────────────────────────────────────────────────


def load() -> tuple[Snapshot, EvidenceFile]:
    snapshot = Snapshot.load_csv(SNAPSHOT_CSV)
    evidence = EvidenceFile.from_dict(json.loads(EVIDENCE_JSON.read_text()))
    return snapshot, evidence


def velocities(snapshot: Snapshot, evidence: EvidenceFile) -> dict[str, Velocity]:
    """Match each fetched artifact back to its observation in the snapshot."""
    observed = snapshot.by_name()
    out: dict[str, Velocity] = {}
    for artifact in evidence.artifacts.values():
        earlier = observed.get(artifact.name)
        if earlier is None or artifact.popularity_kind != "stars":
            continue
        later = type(earlier)(
            artifact.name, artifact.popularity, evidence.fetched_on, earlier.domain
        )
        out[artifact.id] = Velocity.between(earlier, later)
    return out


def assessments(evidence: EvidenceFile, speed: dict[str, Velocity]) -> list[Assessment]:
    out: list[Assessment] = []
    for judgement in JUDGEMENTS:
        artifact = evidence.get(judgement.artifact_id)
        if artifact is None:
            continue
        out.append(
            assess(
                artifact,
                speed.get(judgement.artifact_id),
                relevance=judgement.relevance,
                relevance_note=judgement.relevance_note,
                integration_cost=judgement.integration_cost,
                substitutes_our_product=judgement.substitution,
            )
        )
    return out


def _growth(speed: dict[str, Velocity], artifact_id: str) -> str:
    velocity = speed.get(artifact_id)
    if velocity is None:
        return "—"
    return "stalled" if velocity.stalled else f"{velocity.relative_change:+.1%}"



def render_scan(snapshot: Snapshot) -> str:
    signal, report = snapshot.apply()
    lines = [
        "# Dataset quality — what the scrape actually contained",
        "",
        "Read this before any other document here. A pipeline that silently filters to the",
        "interesting rows produces a report that looks identical whether the scrape worked",
        "or failed, so the filtering is reported first and in full.",
        "",
        "```",
        report.report(),
        "```",
        "",
        f"Every row is accounted for: {report.kept} kept plus {report.removed} removed equals",
        f"{report.received} received. The filter raises rather than returning if that fails.",
        "",
        "## Domain verdicts",
        "",
        "| domain | rows | above floor | max stars | verdict |",
        "|---|--:|--:|--:|---|",
    ]
    for item in snapshot.assess_domains():
        lines.append(
            f"| {item.domain} | {item.total} | {item.head} | {item.max_stars} | "
            f"**{item.verdict.upper()}** |"
        )
    lines += [
        "",
        "Three of the five domain queries returned nothing usable. Their maxima are 0, 8 and 1",
        "stars respectively — those are not thin results, they are failed queries, and every",
        "conclusion in these documents is therefore scoped to **AI Agent** and **RAG** only.",
        "",
        "## Why the noise rule is volume AND traction",
        "",
        "An account with a hundred repositories is either a spammer or a major foundation.",
        "Counting alone would delete the most credible publishers in the ecosystem, so an owner",
        "is only removed when high volume comes with no traction anywhere in that volume.",
        "",
        "## What survives",
        "",
        f"{len(signal)} projects, holding {signal.stars_total()} of the",
        f"{snapshot.stars_total()} stars in the file. The signal is 3.5% of the rows and",
        "essentially all of the attention.",
    ]
    return "\n".join(lines) + FOOTER


def render_enterprise(evidence: EvidenceFile, speed: dict[str, Velocity]) -> str:
    lines = [
        "# Enterprise research — Tier 1, all eighteen sections",
        "",
        "Fifteen projects, chosen by relevance to OMNEX rather than by star count. Every",
        "factual claim carries the page it was read from and the date it was read. Judgements",
        "are marked as judgements and live in `engine/scripts/intel_judgements.py`, one record",
        "per project, so a disagreement is a one-line edit rather than an argument with a",
        "paragraph.",
        "",
        "**Architecture sections are inference from public evidence, not insider knowledge.**",
        "",
    ]

    ranked = sorted(
        (j for j in JUDGEMENTS if evidence.get(j.artifact_id)),
        key=lambda j: -j.relevance,
    )
    for judgement in ranked:
        artifact = evidence.get(judgement.artifact_id)
        assert artifact is not None
        lines.extend(_project_sections(artifact, judgement, speed))
    return "\n".join(lines) + FOOTER


def _bullets(items: tuple[str, ...], empty: str = "_none recorded_") -> list[str]:
    return [f"- {item}" for item in items] or [empty]



        "",
        "The top of this ecosystem is not model engineering. Clustering the signal set by what",
        "each project actually is: skills packaging for coding agents dominates, curated lists",
        "come second, and messaging-channel bridges come third. The single highest-starred",
        "project in the entire scan contains ten markdown files and no code.",
        "",
        "**The winners package and distribute. They do not train.**",
        "",

"""Render the intelligence reports from the committed snapshot and evidence.

    python scripts/enrich_intel.py     # fetch → intel/evidence_YYYYMMDD.json
    python scripts/scan_intel.py       # evidence → intel/*.md

Reads only committed files, so the reports regenerate byte-for-byte on a machine
with no network. Every rendered document is then passed through
`omnex.intel.report.verify_document`, and the script exits non-zero if any
document cites evidence that is not in the evidence file or states a figure no
evidence record contains. A report that cannot pass its own verifier does not
get published from here.
"""

